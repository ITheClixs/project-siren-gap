  How Much of the Weight-Space Perception Gap Is Symmetry?
  An Exact Decomposition for Periodic-Activation Networks

Authors:
  Mehmet Demir Guven (Department of Computer Science, ETH Zurich)

Primary category:
  cs.LG

Cross-lists:
  stat.ML   -- the pre-registrations, interval scoring and calibration audit
  cs.CV     -- implicit neural representations; the corpora are image INRs

Comments field:
  {os.environ['PAGES']} pages, {figs} figures, {tables} tables. Code, corpus generators, all
  pre-registrations and the full prediction ledger (hits and misses):
  https://github.com/ITheClixs/project-siren-gap

License:
  CC BY 4.0 (repository code is MIT)

MSC / ACM (optional):
  MSC 68T07, 20C35 ; ACM I.2.6, I.5.1

Abstract ({len(abstract)} chars; arXiv's limit is 1920 and applies to this field, not to the PDF):
{abstract}

Notes for the upload
--------------------
* Upload dist/arxiv/arxiv-submission.tar.gz. It holds paper.tex, tables/ and only the figures the
  document includes. No .bib is needed -- the bibliography is an inline thebibliography, so
  arXiv's TeX Live compiles it in one pass.
* This script compiles that exact tarball in a clean directory and fails if a reference is
  unresolved, so what is uploaded is what was verified.
* Do not attach the corpora as ancillary files: they regenerate from the committed generator, and
  the repository link above is the data-availability statement.
